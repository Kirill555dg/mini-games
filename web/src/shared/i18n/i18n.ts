let locale = "ru";
try {
  locale = localStorage.getItem("mini-games-language") || (navigator.language.startsWith("ru") ? "ru" : "en");
} catch {
  /* Storage is optional. */
}
if (!["ru", "en"].includes(locale)) locale = "ru";
export const language = () => locale;
export const dateLocale = () => (locale === "ru" ? "ru-RU" : "en-GB");
export function setLanguage(value: string) {
  locale = value === "en" ? "en" : "ru";
  try {
    localStorage.setItem("mini-games-language", locale);
  } catch {
    /* Optional. */
  }
}
export function t(key: string, values: Record<string, string | number> = {}) {
  const text = (locale === "en" ? en : ru)[key] || ru[key] || key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
export function translated(game: GameSpec | undefined, field: "title" | "description" | "rules") {
  return locale === "en" ? game?.translations?.en?.[field] || game?.[field] : game?.[field];
}
export function sideName(game: GameSpec | undefined, seat: number) {
  return game?.sides?.[locale]?.[seat] || t("player", { n: seat + 1 });
}
